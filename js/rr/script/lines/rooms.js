// Who is who. In a room (talk.js talkAtWait) the seats are filled by PAIRS OF PEOPLE FROM DIFFERENT
// TEAMS: `a` and `b` are on different teams, and `a` is the one the ending is about (the one who
// lost the scramble, talks in their sleep, is scared of flying, is clapped or booed onto the mat,
// plays the prank). `c` and `d` are whoever else got a seat: they may be a's partner, b's partner
// or a third team, so a c/d line is always one anybody in the room could say, never one that needs
// to know whose partner they are, and every c/d turn is `opt` (a room can be just a and b).
// The superteam is the exception: the engine plays it with the first team as `a`,`b` and the
// team it is paired with as `c`,`d`; their lines are still asides, so the scene reads without them.
// `rel` and `relFam` are a's TEAM's relationship, not a's with b, so no line here gates on them and
// no line carries a `rel:` variant. `allied`, `rival` and `bandX` are between a's team and the other.
// Nobody counts heads; nobody names a partner they can't (only `{partner}`, a's own).
