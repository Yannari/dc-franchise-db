#!/usr/bin/env python3
"""
Step 3 of the D1 learning project: turn the existing JSON into SQL.

This script READS players_database.json + seasons_database.json and WRITES seed.sql.
It never modifies the JSON and never touches the live site.

Run:   python worker/build_seed.py
Then:  cd worker && npx wrangler d1 execute dc-franchise --remote --file seed.sql
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

def sql(v):
    """Turn a Python value into a literal we can paste into SQL."""
    if v is None or v == "":
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return str(v)
    # text: escape single quotes by doubling them (SQL's escape rule)
    return "'" + str(v).replace("'", "''") + "'"

def as_int(v):
    """strategicRank is sometimes 1 and sometimes 'High'. Keep only real numbers."""
    if isinstance(v, bool):
        return None
    if isinstance(v, int):
        return v
    if isinstance(v, float):
        return int(v)
    if isinstance(v, str) and v.strip().lstrip("-").isdigit():
        return int(v.strip())
    return None

with open(os.path.join(ROOT, "players_database.json"), encoding="utf-8") as f:
    players = json.load(f)["players"]
with open(os.path.join(ROOT, "seasons_database.json"), encoding="utf-8") as f:
    seasons = json.load(f)["seasons"]

# Name -> slug lookup, so unbreakableBonds ("Cameron") can become a player id.
name_to_slug = {}
for p in players:
    if p.get("name") and p.get("id"):
        name_to_slug[p["name"].strip().lower()] = p["id"]

valid_slugs = {p["id"] for p in players if p.get("id")}
valid_seasons = {s["seasonNumber"] for s in seasons if s.get("seasonNumber") is not None}

lines = [
    "-- GENERATED by worker/build_seed.py. Do not hand-edit; regenerate instead.",
    "-- Wipes and refills the 4 tables. Safe to re-run any time.",
    "",
    "DELETE FROM bonds;",
    "DELETE FROM appearances;",
    "DELETE FROM seasons;",
    "DELETE FROM players;",
    "",
]

# ---------- players ----------
lines.append("-- players")
for p in players:
    lines.append(
        "INSERT INTO players (id,name,total_seasons,best_placement,wins,"
        "total_challenge_wins,total_immunity_wins,total_reward_wins,"
        "total_votes_against,total_idols_found,total_jury_votes,tier,avg_placement) VALUES ("
        + ",".join([
            sql(p.get("id")),
            sql(p.get("name")),
            sql(p.get("totalSeasons")),
            sql(p.get("bestPlacement")),
            sql(p.get("wins")),
            sql(p.get("totalChallengeWins")),
            sql(p.get("totalImmunityWins")),
            sql(p.get("totalRewardWins")),
            sql(p.get("totalVotesAgainst")),
            sql(p.get("totalIdolsFound")),
            sql(p.get("totalJuryVotes")),
            sql(p.get("tier")),
            sql(p.get("avgPlacement")),
        ]) + ");"
    )

# ---------- seasons ----------
lines += ["", "-- seasons"]
for s in seasons:
    winner = s.get("winner") or {}
    lines.append(
        "INSERT INTO seasons (season_number,title,subtitle,cast_size,episode_count,"
        "winner_slug,theme,status) VALUES ("
        + ",".join([
            sql(s.get("seasonNumber")),
            sql(s.get("title")),
            sql(s.get("subtitle")),
            sql(s.get("castSize")),
            sql(s.get("episodeCount")),
            sql(winner.get("playerSlug")),
            sql(s.get("theme")),
            sql(s.get("status")),
        ]) + ");"
    )

# ---------- appearances + bonds (flattened from seasonDetails[]) ----------
app_rows, bond_rows = [], []
seen_app, seen_bond = set(), set()
skipped_season, skipped_bond_name, dup_app = [], [], []

for p in players:
    pid = p.get("id")
    for d in (p.get("seasonDetails") or []):
        sn = d.get("season")
        if sn not in valid_seasons:
            skipped_season.append((pid, sn))
            continue
        if (pid, sn) in seen_app:
            dup_app.append((pid, sn))
            continue
        seen_app.add((pid, sn))
        app_rows.append(
            "INSERT INTO appearances (player_id,season_number,placement,status,tribe,"
            "challenge_wins,immunity_wins,reward_wins,votes_received,idols_found,"
            "strategic_rank,jury_votes,final_vote) VALUES ("
            + ",".join([
                sql(pid), sql(sn),
                sql(d.get("placement")),
                sql(d.get("status")),
                sql(d.get("tribe")),
                sql(d.get("challengeWins")),
                sql(d.get("immunityWins")),
                sql(d.get("rewardWins")),
                sql(d.get("votesReceived")),
                sql(d.get("idolsFound")),
                sql(as_int(d.get("strategicRank"))),
                sql(d.get("juryVotes")),
                sql(d.get("finalVote")),
            ]) + ");"
        )
        for ally in (d.get("unbreakableBonds") or []):
            slug = name_to_slug.get(str(ally).strip().lower())
            if not slug or slug not in valid_slugs or slug == pid:
                skipped_bond_name.append((pid, sn, ally))
                continue
            key = (pid, slug, sn)
            if key in seen_bond:
                continue
            seen_bond.add(key)
            bond_rows.append(
                "INSERT INTO bonds (player_id,ally_id,season_number) VALUES ("
                + ",".join([sql(pid), sql(slug), sql(sn)]) + ");"
            )

lines += ["", "-- appearances"] + app_rows
lines += ["", "-- bonds"] + bond_rows
lines.append("")

out = os.path.join(HERE, "seed.sql")
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

print(f"wrote {out}")
print(f"  players     : {len(players)}")
print(f"  seasons     : {len(seasons)}")
print(f"  appearances : {len(app_rows)}")
print(f"  bonds       : {len(bond_rows)}")
if skipped_season:
    print(f"  ! skipped {len(skipped_season)} appearances w/ unknown season: {skipped_season[:10]}")
if dup_app:
    print(f"  ! skipped {len(dup_app)} duplicate (player,season) rows: {dup_app[:10]}")
if skipped_bond_name:
    print(f"  ! skipped {len(skipped_bond_name)} bonds w/ unmatched name: {skipped_bond_name[:10]}")
