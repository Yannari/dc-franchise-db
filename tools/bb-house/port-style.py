# tools/bb-house/port-style.py — the stage CSS of the approved mockup, scoped for the simulator.
#
# mockup/mockup-bb-house-v2.html is the approved design. Its stage rules are written for a page
# of their own (.stage, .cam, .set, .l3 ...), which would restyle the simulator's own classes,
# so every selector is scoped under `.bbx` and every @keyframes is renamed `bbx-*`. Output:
# js/vp-bb-ep/style.js. Re-run after changing the mockup's stage CSS:  python tools/bb-house/port-style.py
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(ROOT, 'mockup', 'mockup-bb-house-v2.html'), encoding='utf-8').read()
css = src[src.index('<style>') + 7: src.index('</style>')]
start = css.index('.stage{')
end = css.index('body.tvm')
css = css[start:end]
# per-room photo rules are set inline by the viewer (the season decides the file)
css = re.sub(r'^\s*(body\[[^\n]*|\.set-[a-z]+\.photo\{background:url[^\n]*)\n', '', css, flags=re.M)
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)

names = set(re.findall(r'@keyframes\s+([\w-]+)', css))

def scope_block(block):
    out = []
    i = 0
    while i < len(block):
        j = block.find('{', i)
        if j < 0:
            break
        sel = block[i:j].strip()
        if sel.startswith('@keyframes'):
            depth, k = 1, j + 1
            while depth:
                depth += {'{': 1, '}': -1}.get(block[k], 0); k += 1
            name = sel.split()[1]
            out.append(f'@keyframes bbx-{name}' + block[j:k])
            i = k
            continue
        if sel.startswith('@media'):
            depth, k = 1, j + 1
            while depth:
                depth += {'{': 1, '}': -1}.get(block[k], 0); k += 1
            out.append(sel + '{' + scope_block(block[j + 1:k - 1]) + '}')
            i = k
            continue
        k = block.find('}', j)
        body = block[j:k + 1]
        sels = ','.join('.bbx ' + s.strip() for s in sel.split(','))
        out.append(sels + body)
        i = k + 1
    return '\n'.join(out)

scoped = scope_block(css)
for n in sorted(names, key=len, reverse=True):
    scoped = re.sub(r'(animation:[^;}]*?)\b' + re.escape(n) + r'\b', lambda m: m.group(1) + 'bbx-' + n, scoped)
scoped = scoped.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')
fonts = "@import url('https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,300..900&family=Chakra+Petch:wght@500;600;700&display=swap');"
js = ('// GENERATED by tools/bb-house/port-style.py from mockup/mockup-bb-house-v2.html. Do not edit by hand.\n'
      f'export const BBX_FONTS = "{fonts}";\n'
      f'export const BBX_CSS = `{scoped}`;\n')
os.makedirs(os.path.join(ROOT, 'js', 'vp-bb-ep'), exist_ok=True)
open(os.path.join(ROOT, 'js', 'vp-bb-ep', 'style.js'), 'w', encoding='utf-8').write(js)
print('ok', len(js), 'bytes;', len(names), 'keyframes')
