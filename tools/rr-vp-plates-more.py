# The user's finished plates the viewer wasn't using (2026-10-20: 222 of 642, "why did i do all that work if u dont even
# use them all"), each looked at and given a place: another standing shot at a challenge (talk), another angle on the
# action (alt; alt2 for a challenge's second half), another arrival, another Chill Zone angle (mat), or a view Don
# narrates over (views; `at: mat` ones for the Chill Zone). What can't be used says why (LEFT_OUT), and the test holds
# every file in the frames folder to one or the other.
#
#   python tools/rr-vp-plates-more.py tools/rr-vp-plates-more.txt  ->  js/vp-rr-ep/plates-more.js
#
# The list: one plate a line, `place | file | slot | g | x | more-json`; slot is talk:<stretch>, alt:<stretch>,
# arrive, mat, views, or skip:<why>. A `more` with "side" puts it on that side of an Either/Or; "second" makes an alt
# an angle on the second half (act2); "like": "act" copies the stretch's action plate (a cut-out swapped in).
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'tools', 'rr-vp-plates-more.txt')
more, left, props = {}, {}, {}
for line in open(src, encoding='utf-8'):
    line = line.rstrip('\n')
    if not line.strip() or line.lstrip().startswith('#'):
        continue
    cols = [c.strip() for c in line.split('|')]
    cols += [''] * (6 - len(cols))
    place, f, slot, g, x, extra = cols[:6]
    extra = json.loads(extra) if extra else {}
    if place == 'props':
        props.setdefault(f, {}).update(extra)
        continue
    if slot.startswith('skip:'):
        left.setdefault(place, {})[f] = slot[5:]
        continue
    pl = more.setdefault(place, {})
    plate = {'f': f} if f != '-' else {}
    if g != '':
        plate['g'] = float(g) if '.' in g else int(g)
    if x:
        plate['x'] = [int(v) for v in x.split(',')]
    side = extra.pop('side', None)
    second = extra.pop('second', False)
    plate.update(extra)
    kind, _, stretch = slot.partition(':')
    if kind in ('arrive', 'views', 'mat'):
        pl.setdefault(kind, []).append(plate)
        continue
    st = pl.setdefault('st', {}).setdefault(stretch, {})
    if side:
        st = st.setdefault('sides', {}).setdefault(side, {})
    key = 'talk' if kind == 'talk' else ('alt2' if second else 'alt')
    st.setdefault(key, []).append(plate)
for place, ps in props.items():
    more.setdefault(place, {})['props'] = ps

out = os.path.join(ROOT, 'js', 'vp-rr-ep', 'plates-more.js')
with open(out, 'w', encoding='utf-8', newline='\n') as w:
    w.write('// GENERATED by tools/rr-vp-plates-more.py from tools/rr-vp-plates-more.txt: edit the list, not this file.\n')
    w.write('// The user\'s plates the viewer had left out, each given its place (plates.js merges them in), and the ones that\n')
    w.write('// can\'t be used, with why.\n')
    w.write('export const MORE = ' + json.dumps(more, indent=1, ensure_ascii=False) + ';\n\n')
    w.write('export const LEFT_OUT = ' + json.dumps(left, indent=1, ensure_ascii=False) + ';\n')
print('places', len(more), 'left out', sum(len(v) for v in left.values()))
