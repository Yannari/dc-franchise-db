/** The local's line for a team taking its clue: `ending` is the clue scene's (count-ahead, count-behind, read...). */
export function handoverLine(id, ending, rng) {
  const h = HANDOVER[id];
  if (!h) return null;
  const list = (ending === 'count-ahead' && h.ahead) || (ending === 'count-behind' && h.behind) || h.any;
  return list[Math.floor(rng() * list.length) % list.length];
}
